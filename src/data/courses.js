// تطبيع: إضافة ids للدروس وحساب الإجماليات
export const courses = raw.map((c) => {
  const sections = c.sections.map(([title, lessons], si) => ({
    title,
    lessons: lessons.map(([t, min], li) => ({ id: `${c.id}-${si + 1}-${li + 1}`, title: t, min })),
  }))
  const lessons = sections.flatMap((s) => s.lessons)
  return { ...c, sections, lessons, totalMin: lessons.reduce((a, l) => a + l.min, 0) }
})

export const getCourse = (id) => courses.find((c) => c.id === id)
